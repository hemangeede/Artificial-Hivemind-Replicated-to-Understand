import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer


def embed(texts):
    X = TfidfVectorizer().fit_transform(texts).toarray()
    return X / np.linalg.norm(X, axis=1, keepdims=True)   # unit vectors


def mean_pairwise(E):
    S = E @ E.T                                            # cosine similarity
    return S[np.triu_indices(len(E), k=1)].mean()          # no self-pairs / double count


def intra_model(query_resp):
    return {m: mean_pairwise(embed(r)) for m, r in query_resp.items()}


def inter_model(query_resp, a, b):

    texts = query_resp[a] + query_resp[b]
    E = embed(texts)                                       # fit on shared vocabulary
    na = len(query_resp[a])
    return float((E[:na] @ E[na:].T).mean())


def unique_models_in_topN(query_resp, N=5):
    texts, owner = [], []
    for m, rs in query_resp.items():
        texts += rs
        owner += [m] * len(rs)
    owner = np.array(owner)
    E = embed(texts)
    S = E @ E.T
    np.fill_diagonal(S, -1)                                # ignore self
    counts = [len(set(owner[np.argsort(-S[i])[:N]])) for i in range(len(texts))]
    return float(np.mean(counts))


